# =========================================================
# INTEGER (int)
# Whole numbers
# =========================================================

print("\n========== INTEGER ==========")

age = 25

print("Age:", age)

print("Datatype:", type(age))


# =========================================================
# FLOAT
# Decimal numbers
# =========================================================

print("\n========== FLOAT ==========")

price = 99.99

print("Price:", price)

print("Datatype:", type(price))


# =========================================================
# COMPLEX
# Used in advanced mathematics
# j means imaginary number
# =========================================================

print("\n========== COMPLEX ==========")

complex_number = 3 + 4j

print("Complex Number:", complex_number)

print("Datatype:", type(complex_number))


# =========================================================
# BASIC MATHEMATICAL OPERATIONS
# =========================================================

print("\n========== MATHEMATICAL OPERATIONS ==========")

a = 10
b = 3

print("Addition:", a + b)

print("Subtraction:", a - b)

print("Multiplication:", a * b)

print("Division:", a / b)

print("Floor Division:", a // b)

print("Modulus:", a % b)

print("Power:", a ** b)


# =========================================================
# 1. abs()
# Returns positive value
# =========================================================

print("\n1. abs()")

number = -50

print("Absolute Value:", abs(number))


# =========================================================
# 2. round()
# Rounds decimal number
# =========================================================

print("\n2. round()")

marks = 89.6789

print("Rounded Value:", round(marks, 2))


# =========================================================
# 3. pow()
# Power calculation
# =========================================================

print("\n3. pow()")

print("2 Power 5:", pow(2, 5))


# =========================================================
# 4. max()
# Finds largest value
# =========================================================

print("\n4. max()")

print("Maximum Value:", max(10, 50, 30, 90, 20))


# =========================================================
# 5. min()
# Finds smallest value
# =========================================================

print("\n5. min()")

print("Minimum Value:", min(10, 50, 30, 90, 20))


# =========================================================
# 6. sum()
# Adds all numbers
# =========================================================

print("\n6. sum()")

numbers = [10, 20, 30, 40]

print("Total Sum:", sum(numbers))